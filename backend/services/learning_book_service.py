@dataclass
class LearningSection:
    heading: str
    file_path: Path


def _draw_cover_page(
    output_pdf: Path,
    title: str,
    subtitle: str,
    author: str,
    date_str: str,
    template_name: str,
) -> None:
    theme = TEMPLATES.get(template_name, TEMPLATES["Corporate Technical Manual"])
    w, h = A4
    c = canvas.Canvas(str(output_pdf), pagesize=A4)
    c.setFillColor(theme["bg"])
    c.rect(0, 0, w, h, fill=1, stroke=0)

    # Top accent bar
    c.setFillColor(theme["accent"])
    c.rect(0, h - 28 * mm, w, 28 * mm, fill=1, stroke=0)
    c.setFillColor(theme["primary"])
    c.rect(0, h - 31 * mm, w, 3 * mm, fill=1, stroke=0)

    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 12)
    c.drawString(20 * mm, h - 18 * mm, f"PDF STUDIO  |  {template_name.upper()}")

    # Title block
    c.setFillColor(theme["text"])
    c.setFont("Helvetica-Bold", 28)
    c.drawString(20 * mm, h - 85 * mm, title[:60])

    c.setFillColor(theme["muted"])
    c.setFont("Helvetica", 15)
    c.drawString(20 * mm, h - 98 * mm, subtitle[:90])

    # Divider
    c.setStrokeColor(theme["primary"])
    c.setLineWidth(2)
    c.line(20 * mm, h - 108 * mm, w - 20 * mm, h - 108 * mm)

    # Metadata block
    c.setFillColor(theme["text"])
    c.setFont("Helvetica-Bold", 11)
    c.drawString(20 * mm, 45 * mm, f"Author: {author}")
    c.setFont("Helvetica", 11)
    c.drawString(20 * mm, 37 * mm, f"Published: {date_str}")
    c.setFillColor(theme["muted"])
    c.setFont("Helvetica", 9)
    c.drawString(20 * mm, 22 * mm, "Generated by PDF Studio – Team Document Publishing Platform")

    c.showPage()
    c.save()


def _draw_toc_page(
    output_pdf: Path,
    entries: list[tuple[str, int]],
    template_name: str,
) -> None:
    theme = TEMPLATES.get(template_name, TEMPLATES["Corporate Technical Manual"])
    w, h = A4
    c = canvas.Canvas(str(output_pdf), pagesize=A4)
    c.setFillColor(theme["accent"])
    c.setFont("Helvetica-Bold", 20)
    c.drawString(20 * mm, h - 28 * mm, "Table of Contents")

    c.setStrokeColor(theme["primary"])
    c.setLineWidth(1.5)
    c.line(20 * mm, h - 32 * mm, w - 20 * mm, h - 32 * mm)

    y = h - 46 * mm
    c.setFont("Helvetica", 11)
    for idx, (heading, page_num) in enumerate(entries, start=1):
        if y < 25 * mm:
            c.showPage()
            y = h - 30 * mm
        c.setFillColor(theme["text"])
        c.drawString(22 * mm, y, f"{idx}. {heading[:75]}")
        c.setFillColor(theme["muted"])
        c.drawRightString(w - 20 * mm, y, f"Page {page_num}")
        y -= 9 * mm

    c.showPage()
    c.save()


def _render_section_image_pdf(image_path: Path, output_pdf: Path) -> None:
    """Render a sketchnote/image preserving original orientation and quality."""
    with Image.open(image_path) as raw_img:
        img = ImageOps.exif_transpose(raw_img)
        if img.mode != "RGB":
            img = img.convert("RGB")
        iw, ih = img.size
        page_sz = landscape(A4) if iw > ih else portrait(A4)
        pw, ph = page_sz
        margin = 12 * mm
        avail_w = pw - 2 * margin
        avail_h = ph - 2 * margin - 10 * mm  # reserve header/footer space
        scale = min(avail_w / iw, avail_h / ih)
        dw, dh = iw * scale, ih * scale
        x = (pw - dw) / 2.0
        y = (ph - dh) / 2.0

        c = canvas.Canvas(str(output_pdf), pagesize=page_sz)
        buf = BytesIO()
        img.save(buf, format="PNG", optimize=True)
        buf.seek(0)
        c.drawImage(ImageReader(buf), x, y, width=dw, height=dh, preserveAspectRatio=True)
        c.showPage()
        c.save()


def _overlay_header_footer(
    page_w: float,
    page_h: float,
    header_text: str,
    page_num: int,
    total_pages: int,
) -> PdfReader:
    buf = BytesIO()
    c = canvas.Canvas(buf, pagesize=(page_w, page_h))
    c.setFont("Helvetica", 8)
    c.setFillColor(colors.HexColor("#64748B"))
    c.drawString(14 * mm, page_h - 10 * mm, header_text[:80])
    c.drawRightString(page_w - 14 * mm, 8 * mm, f"Page {page_num} of {total_pages}")
    c.save()
    buf.seek(0)
    return PdfReader(buf)


def create_learning_book(
    output_path: Path,
    title: str,
    subtitle: str,
    author: str,
    date_str: str,
    template_name: str,
    sections: list[LearningSection],
) -> dict[str, int | str]:
    """Generate a complete Learning Book PDF with cover, TOC, bookmarks, headers, and metadata."""
    if not sections:
        raise ValueError("At least one section or sketchnote is required.")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="pdfstudio_book_") as tmp_dir:
        tmp = Path(tmp_dir)
        cover_pdf = tmp / "00_cover.pdf"
        _draw_cover_page(cover_pdf, title, subtitle, author, date_str, template_name)

        # Render all section PDFs first to compute exact TOC page numbers
        section_pdfs: list[tuple[str, Path, int]] = []
        running_page = 3  # Page 1 = Cover, Page 2 = TOC
        for idx, sec in enumerate(sections, start=1):
            ext = sec.file_path.suffix.lower()
            sec_pdf = tmp / f"sec_{idx}.pdf"
            if ext in IMAGE_EXTENSIONS:
                _render_section_image_pdf(sec.file_path, sec_pdf)
            elif ext in DOCUMENT_EXTENSIONS:
                convert_document_to_pdf(sec.file_path, sec_pdf)
            elif ext in PDF_EXTENSIONS:
                verify_pdf_file(sec.file_path)
                sec_pdf = sec.file_path
            else:
                raise ValueError(f"Unsupported section file type: {ext}")

            sec_reader = PdfReader(str(sec_pdf))
            count = len(sec_reader.pages)
            section_pdfs.append((sec.heading, sec_pdf, running_page))
            running_page += count

        toc_pdf = tmp / "01_toc.pdf"
        _draw_toc_page(
            toc_pdf,
            [(h, p) for h, _, p in section_pdfs],
            template_name,
        )

        # Assemble pages
        writer = PdfWriter()
        cover_reader = PdfReader(str(cover_pdf))
        writer.add_page(cover_reader.pages[0])
        writer.add_outline_item(title="Cover", page_number=0)

        toc_reader = PdfReader(str(toc_pdf))
        toc_start_idx = len(writer.pages)
        for p in toc_reader.pages:
            writer.add_page(p)
        writer.add_outline_item(title="Table of Contents", page_number=toc_start_idx)

        for heading, sec_pdf, _ in section_pdfs:
            sec_start_idx = len(writer.pages)
            r = PdfReader(str(sec_pdf))
            for p in r.pages:
                writer.add_page(p)
            writer.add_outline_item(title=heading, page_number=sec_start_idx)

        # Stamp headers/footers on pages after cover
        total_pages = len(writer.pages)
        for idx in range(1, total_pages):
            page = writer.pages[idx]
            pw = float(page.mediabox.width)
            ph = float(page.mediabox.height)
            stamp = _overlay_header_footer(pw, ph, f"{title} — {author}", idx + 1, total_pages)
            page.merge_page(stamp.pages[0])

        writer.add_metadata(
            {
                "/Title": title,
                "/Author": author,
                "/Subject": subtitle,
                "/Creator": f"PDF Studio ({template_name})",
            }
        )

        with output_path.open("wb") as f:
            writer.write(f)

    page_count = verify_pdf_file(output_path)
    return {
        "output_path": str(output_path),
        "page_count": page_count,
        "file_size_bytes": output_path.stat().st_size,
    }
